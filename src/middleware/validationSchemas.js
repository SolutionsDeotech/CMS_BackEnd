import Joi from 'joi'
import { COMMENT_STATUS, PERMISSIONS, POST_STATUS, USER_ROLES } from '../config/constants.js'

const text = (max = 500) => Joi.string().trim().max(max)
const email = Joi.string().trim().lowercase().email({ tlds: { allow: false } }).max(254)
const id = Joi.alternatives().try(Joi.string().trim().min(1).max(120), Joi.number().integer().positive())

export const authSchemas = {
  register: Joi.object({
    name: text(100).min(2).required(),
    email: email.required(),
    password: Joi.string().min(8).max(128).required(),
    userType: Joi.string().valid(USER_ROLES.ADMIN, USER_ROLES.CONTENT_WRITER).default(USER_ROLES.CONTENT_WRITER),
    phone: text(30).allow(''),
    country: text(100).allow(''),
    bio: text(500).allow(''),
    avatar: Joi.string().uri({ scheme: ['http', 'https', 'data'] }).allow(''),
  }),
  login: Joi.object({
    email: email.required(),
    password: Joi.string().min(1).max(128).required(),
    userType: Joi.string().valid(...Object.values(USER_ROLES)),
  }),
  email: Joi.object({ email: email.required() }),
  verifyOtp: Joi.object({ email: email.required(), otp: Joi.string().pattern(/^\d{6}$/).required() }),
  resetPassword: Joi.object({
    email: email.required(),
    otp: Joi.string().required(),
    password: Joi.string().min(6).max(128),
    newPassword: Joi.string().min(6).max(128),
  }).or('password', 'newPassword'),
  profile: Joi.object({
    name: text(100).min(2),
    email,
    phone: text(30).allow(''),
    country: text(100).allow(''),
    bio: text(500).allow(''),
    avatar: Joi.string().uri({ scheme: ['http', 'https', 'data'] }).allow(''),
  }).min(1),
  changePassword: Joi.object({
    currentPassword: Joi.string().min(1).max(128).required(),
    newPassword: Joi.string().min(8).max(128).required(),
  }),
}

